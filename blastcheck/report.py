"""Step 6: the markdown report. Plain code, no LLM.

The report is for the human reviewing the PR. It leads with the verdict and the
regressions, then shows every test with its fate and the reason, so a reader can see
exactly what blastcheck checked, what it threw away, and why.
"""

from blastcheck.models import Intent, PolicyResult, RejectedTest, ValidationResult


def build_report(
    change_id: str,
    intent: Intent,
    rejected: list[RejectedTest],
    results: list[ValidationResult],
    policy: PolicyResult,
    test_file: str,
) -> str:
    sections = [
        f"# blastcheck report: change {change_id}",
        verdict(results),
        "## What the change is meant to do\n\n" + _one_line(intent.summary),
        _unexplained(intent),
        _regressions(results),
        _tests(results, rejected, test_file),
        _rejected(rejected),
        _risks(intent),
        _notes(intent),
        _policy(policy),
        "---\n\nGenerated by blastcheck. Tests run with `terraform test` (plan-only, mocked "
        "AWS provider); no LLM decides any outcome. A human merges.",
    ]
    return "\n\n".join(s for s in sections if s) + "\n"


def verdict(results: list[ValidationResult]) -> str:
    regressions = [r for r in results if r.outcome == "regression"]
    if regressions:
        return f"**Verdict: REGRESSION FOUND.** {len(regressions)} test(s) pass before this change and fail after it."
    kept = sum(r.outcome == "kept" for r in results)
    return f"**Verdict: no regression found.** {kept} validated test(s) hold after the change."


def _unexplained(intent: Intent) -> str:
    if not intent.unexplained_changes:
        return "## Changes the PR description doesn't explain\n\nNone."
    rows = [
        [f"`{c.address}`", f"`{c.attribute}`", f"`{c.before}`", f"`{c.after}`", c.reason]
        for c in intent.unexplained_changes
    ]
    return "## Changes the PR description doesn't explain\n\n" + _table(
        ["Resource", "Attribute", "Before", "After", "Why it's flagged"], rows
    )


def _regressions(results: list[ValidationResult]) -> str:
    regressions = [r for r in results if r.outcome == "regression"]
    if not regressions:
        return ""
    items = []
    for r in regressions:
        message = r.post.messages[0] if r.post.messages else r.post.status
        items.append(
            f"### `{r.test.name}`\n\n"
            f"**Expectation {r.test.expectation_id}:** {_one_line(r.test.statement)}\n\n"
            f"Passes before the change, fails after it:\n\n```\n{message}\n```"
        )
    return "## Regressions\n\n" + "\n\n".join(items)


def _tests(results: list[ValidationResult], rejected: list[RejectedTest], test_file: str) -> str:
    counts = {outcome: sum(r.outcome == outcome for r in results) for outcome in ("kept", "regression", "discarded")}
    summary = (
        f"{counts['kept']} kept, {counts['regression']} regression(s), "
        f"{counts['discarded']} discarded after running, {len(rejected)} rejected before running."
    )
    rows = [
        [
            f"`{r.test.name}`",
            r.test.expectation_id,
            f"{r.test.kind}, by {r.test.source}",
            r.pre.status,
            r.post.status,
            f"**{r.outcome}**",
            r.reason,
        ]
        for r in results
    ]
    table = _table(["Test", "Expectation", "Kind", "Before", "After", "Outcome", "Reason"], rows)
    return (
        "## Tests\n\n"
        f"{summary}\n\n{table}\n\n"
        f"Kept tests and regressions are in `{test_file}`. Discarded tests are not: "
        "a test that fails on the unchanged module (or errors) is a bad test, not a finding."
    )


def _rejected(rejected: list[RejectedTest]) -> str:
    if not rejected:
        return ""
    items = [f"### `{r.name}` ({r.expectation_id})\n\n{r.reason}\n\n```hcl\n{r.hcl}\n```" for r in rejected]
    return (
        "## Rejected before running\n\n"
        "These LLM-written tests were thrown out without being run.\n\n" + "\n\n".join(items)
    )


def _risks(intent: Intent) -> str:
    if not intent.risks:
        return ""
    order = {"high": 0, "medium": 1, "low": 2}
    lines = [
        f"- **{r.severity}** `{r.address}`: {_one_line(r.statement)}"
        for r in sorted(intent.risks, key=lambda r: order[r.severity])
    ]
    return "## Risks to consider\n\nFrom the LLM's reading of the change; not tested.\n\n" + "\n".join(lines)


def _notes(intent: Intent) -> str:
    if not intent.notes:
        return (
            "## Checks on the LLM's answer\n\n"
            "Nothing dropped or added: every resource and attribute the LLM named exists in the plan."
        )
    return "## Checks on the LLM's answer\n\n" + "\n".join(f"- {note}" for note in intent.notes)


def _policy(policy: PolicyResult) -> str:
    text = f"## Policy checks (Checkov)\n\n{policy.status.capitalize()}: {policy.note}"
    if policy.new_findings:
        rows = [[f"`{f.check_id}`", f.check_name, f"`{f.resource}`"] for f in policy.new_findings]
        text += "\n\n" + _table(["Check", "Name", "Resource"], rows)
    return text


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for row in rows:
        lines.append("| " + " | ".join(_cell(value) for value in row) + " |")
    return "\n".join(lines)


def _cell(value: str) -> str:
    return _one_line(str(value)).replace("|", "\\|")


def _one_line(text: str) -> str:
    return " ".join(text.split())
